/**
 * generate-food-index.js
 * 
 * Generates lightweight index files from foods.ts and remote-foods.json
 * for fast Copilot lookups without loading 7000+ line files.
 * 
 * Output:
 *   data/food-index.json — compact {id, name, cal, unit, unitWeight, source} for every item
 * 
 * Usage:
 *   node scripts/generate-food-index.js
 *   npm run index:foods
 */
const fs = require('fs');
const path = require('path');

// ─── Load static foods from foods.ts ────────────────────────────────────
function loadStaticFoods() {
  const content = fs.readFileSync(
    path.join(__dirname, '../src/data/foods.ts'), 'utf8'
  );
  const foods = [];
  // Regex to extract key fields from TypeScript objects
  const regex = /{\s*id:\s*'([^']+)',\s*name:\s*'([^']+)'(?:,\s*nameMarathi:\s*'([^']*)')?,\s*category:\s*'([^']+)',\s*caloriesPerUnit:\s*([\d.]+)(?:,\s*proteinPerUnit:\s*([\d.]+))?(?:,\s*fatPerUnit:\s*([\d.]+))?(?:,\s*fiberPerUnit:\s*([\d.]+))?,\s*unit:\s*'([^']+)'(?:,\s*unitWeight:\s*([\d.]+))?/g;
  let match;
  while ((match = regex.exec(content)) !== null) {
    foods.push({
      id: match[1],
      name: match[2],
      cat: match[4],
      cal: parseFloat(match[5]),
      pro: match[6] ? parseFloat(match[6]) : undefined,
      fat: match[7] ? parseFloat(match[7]) : undefined,
      fib: match[8] ? parseFloat(match[8]) : undefined,
      unit: match[9],
      wt: match[10] ? parseFloat(match[10]) : undefined,
      src: 'static',
    });
  }
  return foods;
}

// ─── Load remote foods from remote-foods.json ───────────────────────────
function loadRemoteFoods() {
  const filePath = path.join(__dirname, '../data/remote-foods.json');
  if (!fs.existsSync(filePath)) return [];
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  return (data.foods || []).map(f => ({
    id: f.id,
    name: f.name,
    cat: f.category,
    cal: f.caloriesPerUnit,
    pro: f.proteinPerUnit,
    fat: f.fatPerUnit,
    fib: f.fiberPerUnit,
    unit: f.unit,
    wt: f.unitWeight,
    src: 'remote',
  }));
}

// ─── Generate ───────────────────────────────────────────────────────────
function main() {
  const staticFoods = loadStaticFoods();
  const remoteFoods = loadRemoteFoods();
  const all = [...staticFoods, ...remoteFoods];

  // Sort by category then name for readability
  all.sort((a, b) => {
    if (a.cat !== b.cat) return a.cat.localeCompare(b.cat);
    return a.name.localeCompare(b.name);
  });

  // Category summary
  const catCounts = {};
  for (const f of all) {
    catCounts[f.cat] = (catCounts[f.cat] || 0) + 1;
  }

  const output = {
    _comment: 'Auto-generated by scripts/generate-food-index.js — DO NOT EDIT',
    generatedAt: new Date().toISOString().split('T')[0],
    totalItems: all.length,
    staticCount: staticFoods.length,
    remoteCount: remoteFoods.length,
    categoryCounts: catCounts,
    foods: all,
  };

  const outPath = path.join(__dirname, '../data/food-index.json');
  fs.writeFileSync(outPath, JSON.stringify(output, null, 2) + '\n', 'utf8');

  console.log(`Food index generated: ${outPath}`);
  console.log(`  Static: ${staticFoods.length} | Remote: ${remoteFoods.length} | Total: ${all.length}`);
  console.log(`  Categories:`, catCounts);
}

main();
